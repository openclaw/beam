// Run with node schema/packet-generate.mjs [--check].
import { readFileSync, writeFileSync } from "node:fs";

const source = new URL("./packet-v2.schema.json", import.meta.url);
const target = new URL("./packet-v2.ts", import.meta.url);
const spec = JSON.parse(readFileSync(source, "utf8"));

function type(s, indent = "") {
  if (Object.hasOwn(s, "const")) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.type === "array") return type(s.items, indent) + "[]";
  if (s.type !== "object") return s.type;
  const lines = Object.entries(s.properties).map(([k, field]) =>
    indent + "  " + k + (s.required.includes(k) ? "" : "?") + ": " + type(field, indent + "  ") + ";"
  );
  return "{\n" + lines.join("\n") + "\n" + indent + "}";
}

// Compile the structural schema. Byte, UTF-16, duplicate-key, calendar and
// scalar rules intentionally live alongside JSON Schema (see conformance).
function conditions(s, value) {
  const quote = JSON.stringify;
  if (Object.hasOwn(s, "const")) return [value + " === " + quote(s.const)];
  if (s.enum) return ["(" + s.enum.map((v) => value + " === " + quote(v)).join(" || ") + ")"];
  if (s.type === "boolean") return ["typeof " + value + ' === "boolean"'];
  if (s.type === "string") {
    const checks = ["typeof " + value + ' === "string"'];
    if (s.minLength !== undefined && s.minLength === s.maxLength) {
      checks.push(value + ".length === " + s.minLength);
    } else {
      if (s.minLength) checks.push(value + ".length >= " + s.minLength);
      if (s.maxLength !== undefined) checks.push(value + ".length <= " + s.maxLength);
    }
    if (s.pattern) checks.push(regex(s.pattern) + ".test(" + value + ")");
    if (s.not?.pattern) checks.push("!" + regex(s.not.pattern) + ".test(" + value + ")");
    if (s.format === "date-time") checks.push("isInstant(" + value + ")");
    return checks;
  }
  if (s.type === "array") {
    return ["Array.isArray(" + value + ")", value + ".length >= " + s.minItems, value + ".length <= " + s.maxItems,
      value + ".every((item: unknown) => " + conditions(s.items, "item").join(" && ") + ")"];
  }
  if (s.type !== "object" || s.additionalProperties !== false) throw Error("unsupported structural schema");
  const checks = ["record(" + value + ")", "Object.keys(" + value + ").every((key) => " + quote(Object.keys(s.properties)) + ".includes(key))"];
  for (const [name, field] of Object.entries(s.properties)) {
    const path = value + "." + name;
    const test = conditions(field, path).join(" && ");
    checks.push(s.required.includes(name) ? test : "(" + path + " === undefined || (" + test + "))");
  }
  for (const [key, dep] of Object.entries(s.dependentSchemas || {})) {
    checks.push("(" + value + "." + key + " === undefined || (" +
      Object.entries(dep.properties).flatMap(([k, v]) => conditions(v, value + "." + k)).join(" && ") + "))");
  }
  return checks;
}

function regex(s) {
  // JS $ can match immediately before a final newline. The Go wire validator
  // requires an actual end-of-string for IDs and enumerated source names.
  const pattern = s.endsWith("$") ? s.slice(0,-1) + "(?![\\s\\S])" : s;
  return "/" + pattern.replaceAll("/", "\\/") + "/u";
}

const runtime = readFileSync(new URL("./packet-runtime.ts.in", import.meta.url), "utf8");
const file = "// Generated by schema/packet-generate.mjs from packet-v2.schema.json.\n" +
  "export type BeamPacket = " + type(spec) + ";\n\n" + runtime +
  "\nfunction conforms(value: unknown): value is BeamPacket {\n  return " +
  conditions(spec, "value").join(" &&\n    ") + ";\n}\n";
if (process.argv.includes("--check")) {
  if (file !== readFileSync(target, "utf8")) throw Error("generated Beam validator is stale");
} else {
  writeFileSync(target, file);
}
